"""Build the course website in docs/ (an R Markdown site, like NRES 746 and NRES 470).

    python build_site.py                      re-render the site from the existing pages
    python build_site.py path/to/export.docx  also refresh the syllabus pages first

The syllabus lives in the Claude Doc. No Word or Markdown copy is kept in the repo. To refresh
the website after the doc changes:
1. Export the doc as PDF and save it over syllabus/NRES701A_Syllabus_v5_DRAFT.pdf (rename the
   file and SYLLABUS_PDF below when the version changes).
2. Export the doc as Word (or Markdown) to a temporary location and pass its path to this
   script. It is split into docs/index.Rmd (home page = syllabus) and docs/schedule.Rmd
   (schedule + readings). Those two files are GENERATED: do not edit them by hand.
3. Delete the temporary export.

Every run copies the syllabus PDF to docs/Syllabus.pdf and runs rmarkdown::render_site("docs").
The other pages (docs/lectures.Rmd, docs/Links.Rmd) and docs/_site.yml are edited by hand.
"""
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = ROOT / "docs"
SYLLABUS_PDF = ROOT / "syllabus" / "NRES701A_Syllabus_v5_DRAFT.pdf"
SITE_URL = "https://kevintshoemaker.github.io/Causal-Inference/"
TERM = "Spring 2027"

# RStudio's bundled pandoc (the pandoc on PATH is 1.17, too old for rmarkdown's site templates)
PANDOC_DIR = Path(r"C:\Program Files\RStudio\resources\app\bin\quarto\bin\tools")
RSCRIPT = Path(r"C:\Program Files\R\R-4.5.1\bin\Rscript.exe")

HEADER = """---
title: "{title}"
author: "{author}"
date: "{date}"
output:
  html_document:
    theme: flatly
    toc: {toc}
    toc_float: {toc}
    toc_depth: 2
---

<!-- GENERATED by build_site.py from the syllabus. Do not edit by hand. -->

"""


def syllabus_markdown(export):
    out = subprocess.run(
        [str(PANDOC_DIR / "pandoc.exe"), str(export), "-t", "gfm", "--wrap=none"],
        check=True, capture_output=True, encoding="utf-8",
    )
    md = out.stdout
    # "\[to be announced\]" would be read as display math by R Markdown; plain brackets are fine
    md = md.replace("\\[", "[").replace("\\]", "]")
    # schedule table: the dash counts in the separator row set the relative column widths
    md = md.replace("|----|----|----|----|", "|--|" + "-" * 26 + "|" + "-" * 14 + "|" + "-" * 10 + "|")
    return md


def split_sections(md):
    """Return (preamble, [(heading, body), ...]) split at level-2 headings."""
    parts = re.split(r"^## (.+)$", md, flags=re.M)
    preamble = parts[0]
    sections = [(parts[i].strip(), parts[i + 1].strip("\n")) for i in range(1, len(parts), 2)]
    return preamble, sections


def write_syllabus_pages(export):
    preamble, sections = split_sections(syllabus_markdown(export))
    names = [h for h, _ in sections]
    for needed in ("Course schedule", "Readings by week"):
        if needed not in names:
            raise SystemExit(f"Syllabus has no '## {needed}' section; update build_site.py")

    # Preamble: drop the "# Welcome" title and the subtitle line (both go in the page header)
    lines = preamble.strip("\n").split("\n")
    assert lines[0].startswith("# "), lines[0]
    title = lines[0][2:].strip()
    body = "\n".join(lines[1:]).strip("\n").split("\n\n", 1)
    subtitle, intro = body[0].strip(), body[1]
    course_name = subtitle.split(",")[0]  # "Causal Inference and Analysis"
    intro = intro.rstrip()
    if SITE_URL not in intro:  # the syllabus itself normally carries the website line
        intro += f"\\\n**Course website:** <{SITE_URL}>"
    intro += "\\\n**Syllabus (PDF):** [download the syllabus as a PDF](Syllabus.pdf)\n"

    home, sched = [intro], []
    for heading, text in sections:
        if heading == "Course schedule":
            home.append(
                "## Course schedule\n\nThe week-by-week schedule, with each week's required "
                "readings, is on the [Schedule](schedule.html) page."
            )
            sched.append(text)
        elif heading == "Readings by week":
            sched.append(f"## {heading}\n\n{text}")
        else:
            home.append(f"## {heading}\n\n{text}")

    (DOCS / "index.Rmd").write_text(
        HEADER.format(title=title, author=course_name, date=TERM, toc="yes") + "\n\n".join(home) + "\n",
        encoding="utf-8",
    )
    (DOCS / "schedule.Rmd").write_text(
        HEADER.format(title="Schedule", author="NRES 701A", date=TERM, toc="no")
        + "Note: this schedule is a draft and is subject to change. Please check for updates!\n\n"
        + "\n\n".join(sched) + "\n",
        encoding="utf-8",
    )


def main():
    if len(sys.argv) > 1:
        write_syllabus_pages(Path(sys.argv[1]))
    shutil.copyfile(SYLLABUS_PDF, DOCS / "Syllabus.pdf")

    subprocess.run(
        [str(RSCRIPT), "-e",
         f"Sys.setenv(RSTUDIO_PANDOC='{PANDOC_DIR.as_posix()}'); rmarkdown::render_site('{DOCS.as_posix()}')"],
        check=True,
    )


if __name__ == "__main__":
    main()
